import 'dart:convert';

import 'models.dart';

class ParsedOutput {
  const ParsedOutput({
    required this.text,
    required this.reasoning,
    required this.toolCalls,
  });

  final String text;
  final String reasoning;
  final List<ToolCall> toolCalls;
}

/// Parses the Open WebUI chat format: history.messages, output items,
/// reasoning and tool calls.
class ChatCodec {
  static final _detailsBlock = RegExp(r'<details[^>]*>[\s\S]*?</details>');
  static final _thinkBlock = RegExp(r'<think[^>]*>([\s\S]*?)</think>');

  static LoadedChat decode(Map<String, dynamic> json) {
    final chat = json['chat'] is Map
        ? Map<String, dynamic>.from(json['chat'] as Map)
        : <String, dynamic>{};
    final title = (json['title'] ?? chat['title'] ?? '').toString();

    final messages = <ChatMessage>[];
    final history = chat['history'];

    if (history is Map && history['messages'] is Map) {
      final raw = Map<String, dynamic>.from(history['messages'] as Map);
      var currentId = history['currentId']?.toString();
      final seen = <String>{};
      final chain = <Map>[];
      while (currentId != null &&
          raw[currentId] is Map &&
          seen.add(currentId)) {
        final entry = raw[currentId] as Map;
        chain.add(entry);
        currentId = entry['parentId']?.toString();
      }
      for (final entry in chain.reversed) {
        final message = _message(entry);
        if (message != null) messages.add(message);
      }
    } else if (chat['messages'] is List) {
      for (final entry in chat['messages'] as List) {
        if (entry is! Map) continue;
        final message = _message(entry);
        if (message != null) messages.add(message);
      }
    }

    String? model;
    final models = chat['models'];
    if (models is List && models.isNotEmpty) {
      model = models.first.toString();
    }
    if (model == null || model.isEmpty) {
      for (final message in messages.reversed) {
        if (message.role == 'assistant' && message.model != null) {
          model = message.model;
          break;
        }
      }
    }

    final rawTitle = title.trim();
    return LoadedChat(
      id: (json['id'] ?? '').toString(),
      title: rawTitle.isEmpty ? 'Chat' : rawTitle,
      model: model,
      messages: messages,
      pinned: json['pinned'] == true,
      archived: json['archived'] == true,
    );
  }

  static ChatMessage? _message(Map entry) {
    final role = entry['role']?.toString();
    if (role != 'user' && role != 'assistant') return null;

    final content = _content(entry['content']);
    final output = entry['output'];

    var text = content;
    var reasoning = '';
    final toolCalls = <ToolCall>[];
    var outputList = <Map<String, dynamic>>[];

    if (output is List && output.isNotEmpty) {
      outputList = [
        for (final item in output)
          if (item is Map) Map<String, dynamic>.from(item),
      ];
      final parsed = parseOutput(outputList, content);
      text = parsed.text;
      reasoning = parsed.reasoning;
      toolCalls.addAll(parsed.toolCalls);
    } else {
      final think = _thinkBlock.firstMatch(content);
      if (think != null) {
        reasoning = think.group(1)?.trim() ?? '';
        text = content.replaceAll(_thinkBlock, '').trim();
      }
    }

    if (text.isEmpty && toolCalls.isEmpty && reasoning.isEmpty) return null;

    final attachments = <ChatAttachment>[];
    final files = entry['files'];
    if (files is List) {
      for (final file in files) {
        if (file is Map) {
          final parsed = ChatAttachment.fromJson(
            Map<String, dynamic>.from(file),
          );
          if (parsed.id.isNotEmpty || parsed.url.isNotEmpty) {
            attachments.add(parsed);
          }
        }
      }
    }

    // Images generated by a tool arrive in the call result.
    final known = attachments.map((file) => file.url).toSet();
    for (final call in toolCalls) {
      for (final url in _imageUrlsFrom(call.result)) {
        if (!known.add(url)) continue;
        attachments.add(
          ChatAttachment(id: '', name: 'image', type: 'image', url: url),
        );
      }
    }

    final usage = entry['usage'];

    return ChatMessage(
      id: entry['id']?.toString(),
      parentId: entry['parentId']?.toString(),
      role: role!,
      content: text,
      timestamp: (entry['timestamp'] as num?)?.toInt(),
      model: entry['model']?.toString(),
      attachments: attachments,
      toolCalls: toolCalls,
      reasoning: reasoning,
      output: outputList,
      sources: sourceLinksFrom(entry['sources']),
      done: entry['done'] != false,
      usage: usage is Map ? Map<String, dynamic>.from(usage) : null,
    );
  }

  static List<String> _imageUrlsFrom(String? result) {
    if (result == null || !result.contains('images')) return const [];
    try {
      final decoded = jsonDecode(result);
      final images = decoded is Map ? decoded['images'] : null;
      if (images is! List) return const [];
      return [
        for (final image in images)
          if (image is Map && (image['url'] ?? '').toString().isNotEmpty)
            image['url'].toString(),
      ];
    } catch (_) {
      return const [];
    }
  }

  static String _content(Object? raw) {
    if (raw is String) {
      return raw.replaceAll(_detailsBlock, '').trim();
    }
    if (raw is List) {
      final buffer = StringBuffer();
      for (final item in raw) {
        if (item is Map && item['type'] == 'text') {
          buffer.write(item['text'] ?? '');
        }
      }
      return buffer.toString().trim();
    }
    return '';
  }

  static ParsedOutput parseOutput(
    List<Map<String, dynamic>> output,
    String fallback,
  ) {
    final toolCalls = <ToolCall>[];
    final textBuffer = StringBuffer();
    final reasoningBuffer = StringBuffer();

    for (final item in output) {
      final type = item['type']?.toString() ?? '';

      if (type == 'reasoning') {
        final summary = item['summary'];
        final content = item['content'];
        final summaryText = _partsText(summary);
        reasoningBuffer.write(
          summaryText.isNotEmpty ? summaryText : _partsText(content),
        );
        continue;
      }

      if (type == 'message' || type == 'output_text') {
        final content = item['content'];
        if (content is List) {
          textBuffer.write(_partsText(content));
        } else if (content is String) {
          textBuffer.write(content);
        } else if (item['text'] is String) {
          textBuffer.write(item['text']);
        }
        continue;
      }

      if (type == 'function_call') {
        final id = (item['call_id'] ?? item['id'] ?? newId()).toString();
        final name = (item['name'] ?? '').toString();
        final args = item['arguments'];
        toolCalls.add(
          ToolCall(
            id: id,
            name: name.isEmpty ? 'tool' : name,
            arguments: args is String
                ? args
                : (args == null ? '' : jsonEncode(args)),
            status: (item['status'] ?? 'in_progress').toString(),
          ),
        );
        continue;
      }

      if (type == 'function_call_output') {
        final callId = (item['call_id'] ?? '').toString();
        ToolCall? call;
        for (final candidate in toolCalls) {
          if (candidate.id == callId) {
            call = candidate;
            break;
          }
        }
        final result = _partsText(item['output']);
        if (call != null) {
          call.result = result;
          call.status = (item['status'] ?? 'completed').toString();
        }
        continue;
      }

      if (type == 'open_webui:code_interpreter') {
        final code = (item['code'] ?? '').toString();
        final result = _partsText(item['output']);
        final status =
            (item['status'] ?? (result.isEmpty ? 'in_progress' : 'completed'))
                .toString();
        toolCalls.add(
          ToolCall(
            id: (item['id'] ?? newId()).toString(),
            name: 'code_interpreter',
            arguments: code,
            status: status,
            result: status == 'in_progress' ? null : result,
          ),
        );
        continue;
      }

      if (type == 'web_search_call' || type == 'file_search_call') {
        final status = (item['status'] ?? 'completed').toString();
        toolCalls.add(
          ToolCall(
            id: (item['id'] ?? newId()).toString(),
            name: type == 'web_search_call' ? 'web_search' : 'file_search',
            arguments: jsonEncode(item['action'] ?? item['queries'] ?? {}),
            status: status,
            result: status == 'completed' ? '' : null,
          ),
        );
      }
    }

    final text = textBuffer.toString();
    return ParsedOutput(
      text: text.isEmpty ? fallback : text,
      reasoning: reasoningBuffer.toString().trim(),
      toolCalls: toolCalls,
    );
  }

  static String _partsText(Object? parts) {
    if (parts is String) return parts;
    if (parts is! List) return parts == null ? '' : jsonEncode(parts);
    final buffer = StringBuffer();
    for (final part in parts) {
      if (part is Map) {
        final text = part['text'] ?? part['content'];
        if (text is String) {
          buffer.write(text);
        } else if (text is List) {
          buffer.write(_partsText(text));
        }
      } else if (part is String) {
        buffer.write(part);
      }
    }
    return buffer.toString();
  }
}
